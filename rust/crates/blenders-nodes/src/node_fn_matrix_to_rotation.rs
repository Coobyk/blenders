/// `exec` (verbatim — normalize basis then
/// matrix→quat (Shepperd)).
pub fn exec(m: &[[f32; 4]; 4]) -> [f32; 4] {
    // Orthonormalize columns (Gram–Schmidt).
    let mut x = [m[0][0], m[0][1], m[0][2]];
    let mut y = [m[1][0], m[1][1], m[1][2]];
    fn norm(v: [f32; 3]) -> [f32; 3] {
        let l = (v[0] * v[0] + v[1] * v[1] + v[2] * v[2]).sqrt();
        if l < 1e-6 { [0.0; 3] } else { [v[0] / l, v[1] / l, v[2] / l] }
    }
    x = norm(x);
    let d = x[0] * y[0] + x[1] * y[1] + x[2] * y[2];
    y = [y[0] - x[0] * d, y[1] - x[1] * d, y[2] - x[2] * d];
    y = norm(y);
    let z = [
        x[1] * y[2] - x[2] * y[1],
        x[2] * y[0] - x[0] * y[2],
        x[0] * y[1] - x[1] * y[0],
    ];
    let (m00, m01, m02) = (x[0], y[0], z[0]);
    let (m10, m11, m12) = (x[1], y[1], z[1]);
    let (m20, m21, m22) = (x[2], y[2], z[2]);
    let tr = m00 + m11 + m22;
    if tr > 0.0 {
        let s = (tr + 1.0).sqrt() * 2.0;
        [0.25 * s, (m21 - m12) / s, (m02 - m20) / s, (m10 - m01) / s]
    } else if m00 > m11 && m00 > m22 {
        let s = (1.0 + m00 - m11 - m22).sqrt() * 2.0;
        [(m21 - m12) / s, 0.25 * s, (m01 + m10) / s, (m02 + m20) / s]
    } else if m11 > m22 {
        let s = (1.0 + m11 - m00 - m22).sqrt() * 2.0;
        [(m02 - m20) / s, (m01 + m10) / s, 0.25 * s, (m12 + m21) / s]
    } else {
        let s = (1.0 + m22 - m00 - m11).sqrt() * 2.0;
        [(m10 - m01) / s, (m02 + m20) / s, (m12 + m21) / s, 0.25 * s]
    }
}
